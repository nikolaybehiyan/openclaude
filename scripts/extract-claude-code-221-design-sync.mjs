#!/usr/bin/env node
// Decode static asset literals only. Never evaluate code from the executable.
import { createHash } from 'node:crypto'
import { createReadStream } from 'node:fs'
import { mkdir, open, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const EXPECTED_SHA256 =
  '7a181f36ed0fc4fbac6cee4ecf2b615eff93d8b434221fff5d7c878dc5ebf380'
const REGION_OFFSET = 257100000
const REGION_SIZE = 610000
const assets = {
  'SKILL.md': ['u9m', false],
  'storybook/SKILL.md': ['p9m', false],
  'non-storybook/SKILL.md': ['l9m', false],
  'package-build.mjs': ['f9m', true],
  'package-validate.mjs': ['m9m', true],
  'lib/common.mjs': ['h9m', true],
  'lib/detect.mjs': ['g9m', true],
  'lib/bundle.mjs': ['_9m', true],
  'lib/dts.mjs': ['y9m', true],
  'lib/css.mjs': ['b9m', true],
  'lib/source-storybook.mjs': ['S9m', true],
  'lib/source-kit.mjs': ['T9m', true],
  'lib/story-imports.mjs': ['v9m', true],
  'lib/css-fallback.mjs': ['E9m', true],
  'lib/emit.mjs': ['w9m', true],
  'lib/previews.mjs': ['C9m', true],
  'lib/preview-gen-storybook.mjs': ['A9m', true],
  'lib/docs.mjs': ['R9m', true],
  'lib/preview-rebuild.mjs': ['k9m', true],
  'storybook/http-serve.mjs': ['x9m', true],
  'storybook/probe.mjs': ['I9m', true],
  'storybook/compare.mjs': ['P9m', true],
  'package-capture.mjs': ['O9m', true],
  'lib/sync-hashes.mjs': ['D9m', true],
  'lib/remote-diff.mjs': ['H9m', true],
  'resync.mjs': ['M9m', true],
}
const binaryPath = process.argv[2]
const check = process.argv.includes('--check')
if (!binaryPath || binaryPath.startsWith('--')) {
  throw new Error('Usage: node scripts/extract-claude-code-221-design-sync.mjs <audited-binary> [--check]')
}
const hash = createHash('sha256')
for await (const chunk of createReadStream(binaryPath)) hash.update(chunk)
const binarySha256 = hash.digest('hex')
if (binarySha256 !== EXPECTED_SHA256) throw new Error(`Unexpected binary SHA-256: ${binarySha256}`)
const fh = await open(binaryPath, 'r')
const region = Buffer.alloc(REGION_SIZE)
try {
  const { bytesRead } = await fh.read(region, 0, REGION_SIZE, REGION_OFFSET)
  if (bytesRead !== REGION_SIZE) throw new Error('Incomplete audited asset region')
} finally {
  await fh.close()
}
const source = region.toString('utf8')
const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const output = resolve(repo, 'src/skills/bundled/design-sync')
const manifest = { source: 'Claude Code 2.1.221 Darwin arm64', binary_sha256: binarySha256, assets: {} }
const imports = []
const files = []
const digest = value => createHash('sha256').update(value).digest('hex')
async function emit(path, content) {
  if (check) {
    if (await readFile(path, 'utf8') !== content) throw new Error(`Extracted content differs: ${path}`)
  } else {
    await mkdir(dirname(path), { recursive: true })
    await writeFile(path, content, 'utf8')
  }
}
for (const [path, [symbol, module]] of Object.entries(assets)) {
  const anchor = `var ${symbol}=${module ? 'te(function(' : ''}`
  const start = source.indexOf(anchor)
  if (start < 0 || source.indexOf(anchor, start + 1) >= 0) throw new Error(`Ambiguous asset: ${symbol}`)
  let literalStart = start + anchor.length
  if (module) {
    literalStart = source.indexOf('.exports=', literalStart)
    if (literalStart < 0 || literalStart - start > 100) throw new Error(`Missing static export: ${symbol}`)
    literalStart += '.exports='.length
  }
  let scannerError = false
  const scanner = ts.createScanner(ts.ScriptTarget.Latest, false, ts.LanguageVariant.Standard,
    source.slice(literalStart), () => { scannerError = true })
  const token = scanner.scan()
  if (scannerError || (token !== ts.SyntaxKind.StringLiteral && token !== ts.SyntaxKind.NoSubstitutionTemplateLiteral)) {
    throw new Error(`Not a valid static literal: ${symbol}`)
  }
  const content = scanner.getTokenValue()
  const suffix = source.slice(literalStart + scanner.getTextPos(), literalStart + scanner.getTextPos() + 4)
  if (module && suffix !== '});v') throw new Error(`Unexpected module terminator: ${symbol}: ${suffix}`)
  const diskName = path.endsWith('.mjs') ? `${path}.txt` : path
  await emit(resolve(output, diskName), content)
  manifest.assets[path] = {
    symbol,
    literal_byte_offset: REGION_OFFSET + Buffer.byteLength(source.slice(0, literalStart)),
    bytes: Buffer.byteLength(content),
    sha256: digest(content),
  }
  const identifier = `asset${imports.length}`
  imports.push(`import ${identifier} from './design-sync/${diskName}' with { type: 'text' }`)
  if (path !== 'SKILL.md') files.push(`  '${path}': ${identifier},`)
}
await emit(resolve(output, 'claude-code-2.1.221.manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`)
await emit(resolve(output, '../designSyncContent.ts'),
  '// Generated by scripts/extract-claude-code-221-design-sync.mjs.\n' +
  '// .mjs.txt assets are bundled as text, then extracted with their original .mjs names.\n' +
  `${imports.join('\n')}\n\nexport const SKILL_MD: string = asset0\n\n` +
  `export const SKILL_FILES: Record<string, string> = {\n${files.join('\n')}\n}\n`)
process.stdout.write(`${check ? 'Verified' : 'Extracted'} ${Object.keys(assets).length} static assets from ${binarySha256}\n`)
